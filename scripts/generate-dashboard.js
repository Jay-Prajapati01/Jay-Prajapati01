const fs = require('fs');
const path = require('path');
const { getAllRepos, getUser, getPRs, getIssues, getLanguages, getContributions } = require('./github-api');
const { processUserData, processLanguages } = require('./data-processor');
const { escapeXml, COLORS, getLangColor } = require('./svg-utils');

async function generate() {
  try {
    console.log('Fetching GitHub data...');
    const [user, repos, prs, issues, contributions] = await Promise.all([
      getUser(),
      getAllRepos(),
      getPRs(),
      getIssues(),
      getContributions()
    ]);
    
    const stats = processUserData(user, repos, prs, issues, contributions);
    console.log('Stats:', stats);
    
    const langMap = await getLanguages(repos);
    const languages = processLanguages(langMap);
    console.log('Languages:', languages);
    
    const width = 980;
    const height = 320;
    
    let svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}" width="100%" height="100%" preserveAspectRatio="xMidYMid meet">
  <defs>
    <style>
      @font-face { font-family: 'JetBrains Mono'; src: local('JetBrains Mono'), local('IBM Plex Mono'), local('Fira Code'), local('SF Mono'), local('Menlo'); }
      text { font-family: 'JetBrains Mono', 'IBM Plex Mono', 'Fira Code', 'SF Mono', 'Menlo', monospace; }
    </style>
  </defs>
  <rect width="${width}" height="${height}" rx="16" fill="${COLORS.bg}"/>
  <rect width="${width}" height="${height}" rx="16" fill="none" stroke="${COLORS.border}" stroke-width="1.5"/>`;
    
    // Left side: GITHUB.STATS
    const leftX = 48;
    const rightX = width / 2 + 40;
    
    svg += `
  <text x="${leftX}" y="50" font-size="20" fill="${COLORS.header}" font-weight="700" letter-spacing="2">GITHUB.STATS</text>`;
    
    const statsItems = [
      ['Total Stars Earned', stats.totalStars],
      ['Total Contributions', stats.totalContributions],
      ['Public Repositories', stats.publicRepos],
      ['Total PRs', stats.totalPRs],
      ['Total Issues', stats.totalIssues]
    ];
    
    let statsY = 95;
    for (const [label, value] of statsItems) {
      svg += `
  <text x="${leftX}" y="${statsY}" font-size="15" fill="${COLORS.label}">• ${escapeXml(label)}</text>
  <text x="${leftX + 280}" y="${statsY}" font-size="15" fill="${COLORS.value}" font-weight="500">${escapeXml(String(value))}</text>`;
      statsY += 38;
    }
    
    // Right side: MOST.USED.LANGUAGES
    svg += `
  <text x="${rightX}" y="50" font-size="20" fill="${COLORS.header}" font-weight="700" letter-spacing="2">MOST.USED.LANGUAGES</text>`;
    
    // Language bar
    const barX = rightX;
    const barY = 72;
    const barWidth = width - rightX - 48;
    const barHeight = 20;
    
    svg += `
  <rect x="${barX}" y="${barY}" width="${barWidth}" height="${barHeight}" rx="10" fill="${COLORS.separator}"/>`;
    
    let currentX = barX;
    for (const lang of languages) {
      const segWidth = (parseFloat(lang.percentage) / 100) * barWidth;
      svg += `
  <rect x="${currentX}" y="${barY}" width="${segWidth}" height="${barHeight}" rx="0" fill="${getLangColor(lang.name)}"/>`;
      currentX += segWidth;
    }
    
    // Language legend - 2 columns
    let langY = barY + 50;
    const col1X = rightX;
    const col2X = rightX + 230;
    
    for (let i = 0; i < languages.length; i++) {
      const lang = languages[i];
      const x = i % 2 === 0 ? col1X : col2X;
      const y = langY + Math.floor(i / 2) * 36;
      
      svg += `
  <circle cx="${x}" cy="${y - 4}" r="7" fill="${getLangColor(lang.name)}"/>
  <text x="${x + 18}" y="${y}" font-size="14" fill="${COLORS.value}">${escapeXml(lang.name)} ${escapeXml(lang.percentage)}%</text>`;
    }
    
    // Footer - highlighted
    svg += `
  <rect x="${width/2 - 180}" y="${height - 40}" width="360" height="28" rx="6" fill="${COLORS.border}" fill-opacity="0.15"/>
  <text x="${width / 2}" y="${height - 22}" text-anchor="middle" font-size="12" fill="${COLORS.accent}" font-weight="500">Last updated: ${stats.lastUpdated} • Auto-generated by GitHub Dashboard</text>`;
    
    svg += '\n</svg>';
    
    const outPath = path.join(__dirname, '..', 'assets', 'github-dashboard.svg');
    fs.mkdirSync(path.dirname(outPath), { recursive: true });
    fs.writeFileSync(outPath, svg);
    console.log('Generated:', outPath);
  } catch (error) {
    console.error('Failed to generate dashboard:', error);
    process.exit(1);
  }
}

generate();
